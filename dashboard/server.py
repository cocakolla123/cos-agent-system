def render_lite_markdown(text):
    """Small markdown-lite renderer for structured findings text (bullets, **bold**) — a raw
    <pre> block doesn't render any of that, so a bulleted summary just reads as one dense
    paragraph. Escapes HTML first, then applies formatting on top of the escaped text."""
    lines = html.escape(text).splitlines()
    html_parts = []
    in_list = False
    for line in lines:
        stripped = line.strip()
        is_bullet = stripped.startswith("- ") or stripped.startswith("* ")
        if is_bullet:
            if not in_list:
                html_parts.append("<ul>")
                in_list = True
            html_parts.append(f"<li>{stripped[2:].strip()}</li>")
        else:
            if in_list:
                html_parts.append("</ul>")
                in_list = False
            if stripped:
                html_parts.append(f"<p>{stripped}</p>")
    if in_list:
        html_parts.append("</ul>")
    combined = "".join(html_parts)
    return re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", combined)


