# Domain detection is entirely config-driven — CONFIG["domain_keywords"]/["domain_url_keywords"]
# (set by /setup from the deployer's answer to "what's your core job/domain") build the actual
# patterns. Empty lists (no config.json, or a deployment with no domain specialist) produce a
# pattern that matches nothing, so this degrades safely instead of assuming Genesys/CCaaS.
def _alternation_pattern(keywords):
    if not keywords:
        return re.compile(r"(?!)")  # never matches
    return re.compile(r"|".join(re.escape(k) for k in keywords), re.IGNORECASE)


DOMAIN_URL_PATTERN = _alternation_pattern(CONFIG["domain_url_keywords"])
DOMAIN_KEYWORD_PATTERN = _alternation_pattern(CONFIG["domain_keywords"])
# A URL match still needs to look URL-shaped even though the keyword itself might appear in
# plain text too.
DOMAIN_URL_FULL_PATTERN = (
    re.compile(r"https?://\S*(?:" + "|".join(re.escape(k) for k in CONFIG["domain_url_keywords"]) + r")\S*",
               re.IGNORECASE)
    if CONFIG["domain_url_keywords"] else re.compile(r"(?!)")
)


def entry_text_blob(e):
    return " ".join([
        e.get("context", ""), e.get("proposed_tool_call", ""), e.get("short_summary", ""),
        e.get("linked_domain", ""),
    ])


def is_domain_related(e):
    blob = entry_text_blob(e)
    return bool(DOMAIN_URL_FULL_PATTERN.search(blob) or DOMAIN_KEYWORD_PATTERN.search(blob))


def external_link_for(e):
    """Best-effort real deep link for action types with no draft/execute path, so 'do it
    yourself' is a click away instead of a manual search."""
    action_type = e.get("action_type", "")
    entry_id = e.get("id", "")
    if action_type == "ticket_update" and JIRA_HOST:
        ticket_key = entry_id.split(":")[0]
        if re.match(r"^[A-Z]+-\d+$", ticket_key):
            return f"Open ticket in {TICKET_SYSTEM_NAME}", f"{JIRA_HOST}/browse/{ticket_key}"
    if action_type == "calendar_change":
        return "Open Calendar", "https://calendar.google.com/calendar/r"
    # Most domain specialists hold no mutation tool at all (by design — see agents/README.md),
    # so any domain-side recommendation is a "go do it yourself" case regardless of
    # action_type; it's instructed to include a real deep link in its context/proposed text
    # when relevant — surface it if present.
    domain_link = DOMAIN_URL_FULL_PATTERN.search(entry_text_blob(e))
    if domain_link:
        return f"Open in {DOMAIN_TAG}", domain_link.group(0)
    return None, None


