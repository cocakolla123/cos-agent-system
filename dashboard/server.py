class Handler(BaseHTTPRequestHandler):
    def _send_json(self, obj, code=200):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _send_html(self, body):
        b = body.encode()
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(b)))
        self.end_headers()
        self.wfile.write(b)

    _ALLOWED_HOSTS = ("127.0.0.1", "localhost", "[::1]")

    def _origin_ok(self):
        """M12 hardening: reject requests not addressed to localhost.

        Blocks DNS-rebinding (a hostile page pointing its own hostname at
        127.0.0.1 — the browser then sends that hostname in Host) and any
        cross-origin caller. Same-origin browser requests and curl to
        127.0.0.1 pass unchanged.
        """
        if DEMO:
            return True          # read-only fictional data; POSTs never act
        host = (self.headers.get("Host") or "").rsplit(":", 1)[0].lower()
        if host not in self._ALLOWED_HOSTS:
            return False
        origin = self.headers.get("Origin")
        if origin:
            ohost = urlparse(origin).hostname or ""
            if ohost.lower() not in self._ALLOWED_HOSTS:
                return False
        return True

    def do_GET(self):
        if not self._origin_ok():
            self._send_json({"message": "forbidden: non-local Host/Origin"}, 403)
            return
        parsed = urlparse(self.path)
        if parsed.path == "/graph-version":
            self._send_json({"v": dashboard_version()})
            return
        if parsed.path == "/mailbox-status":
            name = (parse_qs(parsed.query).get("name", [""]) or [""])[0]
            try:
                self._send_json(mailbox_status(name))
            except Exception as exc:
                self._send_json({"step": "error", "message": str(exc)}, 500)
            return
        if parsed.path == "/entry-chat-log":
            # Per-task chat history — the page re-renders from this on every
            # task open, and polls it when a slow reply outlives the browser's
            # fetch timeout (Safari kills fetches at ~60s; the model can take
            # longer, and the server finishes + persists regardless).
            qid = (parse_qs(parsed.query).get("id", [""]) or [""])[0]
            logmap = read_json(entry_chat_log_path(), {})
            self._send_json({"messages": logmap.get(qid, [])})
            return
        if parsed.path == "/auth-requests":
            pending = []
            if _accounts is not None:
                try:
                    pending = _accounts.pending_auth_requests(DASHBOARD_DIR)
                except Exception:
                    pending = []
            self._send_json({"requests": pending})
            return
        if parsed.path != "/":
            self.send_response(404)
            self.end_headers()
            return
        requested_ws = (parse_qs(parsed.query).get("workspace", [None]) or [None])[0]
        command_center = render_command_center(requested_ws)
        today_brief = ""
        side_panel = ""
        if _sections is not None:
            try:
                gg, _reg, _act = _sections.load_for_dashboard(COS_DIR, requested_ws)
                today_brief = _sections.render_today_brief(gg, _act)
                cal = _sections.render_calendar(gg, _act)
                if today_brief or cal:
                    # M13: the live deployment's right-hand rail — today's
                    # summary + calendar, fixed on wide screens.
                    side_panel = ('<aside class="side-panel">'
                                  "<h3>Today</h3>%s%s</aside>" % (today_brief, cal))
            except Exception:
                today_brief = ""
                side_panel = ""
        label, daily = latest_daily_log()
        entries = parse_approval_queue()
        pending = sorted(
            (e for e in entries if e.get("status") == "pending"),
            key=lambda e: (PRIORITY_ORDER.get(e.get("priority", "medium"), 1), e.get("created", "")),
        )
