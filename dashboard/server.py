        if self.path == "/approve":
            entry_id = data.get("id", "")
            action_type = data.get("action_type", "")
            tool = ACTION_TOOLS.get(action_type)
            if not tool:
                self._send_json(
                    {"success": False, "message": "no executable tool for this action_type"},
                    400,
                )
                return
            allowed = f"{tool},{BASE_TOOLS}"
            try:
                # bypassPermissions, not dontAsk: dontAsk + --allowedTools works for read-only
                # MCP tools but a real mutating send/write tool can still get denied by an
                # additional permission layer dontAsk doesn't satisfy (confirmed empirically on
                # a real deployment, 2026-07). Scoped to only this one subprocess, only the one
                # tool this specific action needs — get explicit user sign-off before enabling
                # this in a fresh deployment, since it is a real trade-off (see PLAN.md).
                result = subprocess.run(
                    [
                        CLAUDE_BIN, "-p", f"/global:cos-approve-confirmed {entry_id}",
                        "--permission-mode", "bypassPermissions",
                        "--allowedTools", allowed,
                        "--output-format", "text",
                    ],
                    cwd=ORCHESTRATOR_CWD,
                    capture_output=True,
                    text=True,
                    timeout=300,
                )
                output = (result.stdout or result.stderr or "").strip()
                with open(os.path.join(DASHBOARD_DIR, "server.log"), "a") as f:
                    f.write(f"APPROVE {entry_id} returncode={result.returncode} output={output[:3000]!r}\n")
                # Exit code 0 only means the subprocess ran without crashing — a graceful
                # refusal (e.g. a denied tool call) also exits 0, so it can't be treated as
                # "actually sent." Only reload if the entry's own status really flipped.
                still_pending = any(
                    e.get("id") == entry_id and e.get("status") == "pending"
                    for e in parse_approval_queue()
                )
                self._send_json({"success": (result.returncode == 0) and not still_pending, "message": output[:2000] or "(no output)"})
            except subprocess.TimeoutExpired:
                self._send_json(
                    {"success": False, "message": "timed out after 300s — check approval-queue.md manually"},
                    504,
                )
            return

        if self.path == "/save-edit":
            entry_id = data.get("id", "")
            action_type = data.get("action_type", "")
            new_message = data.get("text", "")
            notes = (data.get("notes") or "").strip()
