def render_chat_log():
    text = read_file(os.path.join(DASHBOARD_DIR, "chat-log.md"))
    if not text.strip():
        return "<div class='empty'>No messages yet — say something below.</div>"
    parts = re.split(r"\n\*\*(you|assistant)\*\* _([^_]*)_\n", text)
    html_parts = []
    # parts[0] is leading whitespace; then triples of (role, ts, body)
    for i in range(1, len(parts), 3):
        role, ts, body = parts[i], parts[i + 1], parts[i + 2].strip()
        cls = "chat-you" if role == "you" else "chat-assistant"
        label = "You" if role == "you" else "Assistant"
        html_parts.append(
            f"<div class='chat-msg {cls}'><div class='chat-role'>{label} <span class='meta'>{html.escape(ts)}</span></div>"
            f"<div class='chat-body'>{html.escape(body)}</div></div>"
        )
    return "".join(html_parts)


