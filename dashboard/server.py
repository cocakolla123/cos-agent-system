def set_status(entry_id, new_status, note=None, from_status="pending"):
    """Flip the most recent block matching from_status for entry_id to new_status.
    Bookkeeping only — does not execute anything. Returns True if a block was updated.
    The whole read-modify-write runs under a file lock (M12) so a concurrent
    poll/learn subprocess rewrite can't swallow the flip."""
    path = os.path.join(COS_DIR, "approval-queue.md")
    with _file_lock(path):
        return _set_status_locked(path, entry_id, new_status, note, from_status)


def _set_status_locked(path, entry_id, new_status, note, from_status):
    text = read_file(path)
    pattern = re.compile(
        r"(### " + re.escape(entry_id) + r"\n(?:(?!\n### ).)*?- status: )" + re.escape(from_status),
        re.DOTALL,
    )
    matches = list(pattern.finditer(text))
    if not matches:
        return False
    last = matches[-1]
    new_text = text[: last.start(1)] + new_status + text[last.end() :]
    if note:
        insert_at = new_text.find("\n### ", last.start())
        marker = f"\n- dashboard_note: {note}"
        if insert_at == -1:
            new_text = new_text.rstrip("\n") + marker + "\n"
        else:
            new_text = new_text[:insert_at] + marker + new_text[insert_at:]
    with open(path, "w") as f:
        f.write(new_text)
    if _audit is not None:
        _audit.record(COS_DIR, entry_id, new_status, from_status=from_status,
                      actor="dashboard", detail=note or "")
    return True


MEDIUM_BY_ACTION_TYPE = {"message_send": "Messaging", "ticket_update": "Tickets/comments", "calendar_change": "Calendar/meeting text"}

# proposed_tool_call is stored as a natural-language description of the whole action (e.g.
# 'slack send to X (...) with text: "actual message"') so the drafting agent's intent — who
# it's going to, not just what it says — stays attached to the entry. But that whole sentence
# is NOT the message itself; showing it in an edit box invites editing text that was never
# meant to be part of what gets sent. Extract/rebuild around the quoted portion instead.
TOOL_CALL_TEXT_PATTERN = re.compile(r'with text:\s*"(.*)"\s*$', re.DOTALL)


def extract_message_text(proposed_tool_call):
    m = TOOL_CALL_TEXT_PATTERN.search(proposed_tool_call)
    return m.group(1) if m else proposed_tool_call


def rebuild_tool_call_text(original, new_message):
    m = TOOL_CALL_TEXT_PATTERN.search(original)
    if not m:
        return new_message
    return original[: m.start(1)] + new_message + original[m.end(1) :]


def edit_proposed_text(entry_id, action_type, new_text_raw):
    """Directly overwrite a pending entry's proposed_tool_call with the user's manually edited
    text (no AI redraft). Returns (old_text, changed: bool) or (None, False) if not found."""
    path = os.path.join(COS_DIR, "approval-queue.md")
    text = read_file(path)
    new_text_flat = " ".join(new_text_raw.strip().splitlines())
    pattern = re.compile(
        r"(### " + re.escape(entry_id) + r"\n(?:(?!\n### ).)*?- proposed_tool_call: )"
        r"((?:(?!\n- \w+:|\n### ).)*)",
        re.DOTALL,
    )
    matches = list(pattern.finditer(text))
    if not matches:
        return None, False
    last = matches[-1]
    old_text = last.group(2).strip()
    if old_text == new_text_flat:
        return old_text, False
    new_full = text[: last.start(2)] + new_text_flat + text[last.end(2) :]
    with open(path, "w") as f:
        f.write(new_full)
    # Queue the diff for cos-poll's general scope to fold into personality-profile.md — kept
    # as a cheap local append rather than a synchronous claude call, so "Save edit" stays fast.
    medium = MEDIUM_BY_ACTION_TYPE.get(action_type, "General")
    ts = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    with open(os.path.join(DASHBOARD_DIR, "style-feedback-queue.md"), "a") as f:
        f.write(
            f"\n### {entry_id} {ts}\n- medium: {medium}\n- before: {old_text}\n- after: {new_text_flat}\n"
        )
    return old_text, True


