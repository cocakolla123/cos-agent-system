def parse_inbox():
    text = read_file(os.path.join(COS_DIR, "tasks", "inbox.md"))
    items = []
    for line in text.splitlines():
        m = re.match(r"^-\s*\[(pending|processed)\]\s*(\S+)\s*—\s*(.*)$", line)
        if m:
            items.append({"status": m.group(1), "ts": m.group(2), "text": m.group(3)})
    return items


