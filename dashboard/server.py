def claude_run(job, cmd, cwd=None, capture_output=True, text=True, timeout=None):
    """One claude call through usage.run: only the job's tools are sent, the
    call is capped, its cost is logged, and the daily budget is respected.
    Same shape as subprocess.run's result, so call sites did not change."""
    if _usage is None:
        return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    return _usage.run(cmd, job, DASHBOARD_DIR, cwd=cwd, timeout=timeout)


def spawn_background(cmd, logname, job=None):
    """Popen with output appended to a dashboard log file. Closes the parent's
    handle immediately (the child holds its own dup), so repeated spawns don't
    leak file descriptors. With ``job``, the call runs through usage.py (only
    the job's tools sent, capped, cost logged, daily budget respected)."""
    if job and _usage is not None:
        cmd = [sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), "usage.py"),
               "run", job, DASHBOARD_DIR, "--", *cmd]
    log = open(os.path.join(DASHBOARD_DIR, logname), "a")
    try:
        return subprocess.Popen(cmd, cwd=ORCHESTRATOR_CWD, stdout=log,
                                stderr=subprocess.STDOUT)
    finally:
        log.close()


def draft_missing_async(logname="launchd-poll.log"):
    """Run poll_direct's draft-missing pass in the background. Every path
    that mints tasks (crawl, tick, Poll now) calls this so a new task gets
    its next step right away instead of waiting for a later poll; the pass
    exits before any model call when nothing is missing, so idle calls are
    free."""
    cmd = [sys.executable, os.path.join(TEMPLATE_DASHBOARD_DIR, "poll_direct.py"),
           DASHBOARD_DIR, os.path.join(COS_DIR, "graph"), "--draft-missing"]

    def _run():
        try:
            with open(os.path.join(DASHBOARD_DIR, logname), "a") as f:
                f.write("\n[draft] drafting next steps for tasks without one...\n")
                f.flush()
                subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, timeout=1200,
                               cwd=ORCHESTRATOR_CWD,
                               env={**os.environ, "CLAUDE_BIN": CLAUDE_BIN})
        except Exception:
            pass

    import threading
    threading.Thread(target=_run, daemon=True, name="draft-missing").start()


def maybe_start_learn_loop(message):
    """If ``message`` reads as a correction and self-learning is on: enqueue it,
    launch the /cos-learn loop in the background (non-blocking), and return the
    acknowledgment line to append to the chat reply. Returns "" otherwise.

    The background subprocess only holds LEARN_TOOLS (local file tools + Agent —
    no external mutating tool), so ``dontAsk`` is safe here: the loop can fix its
    own code/config but can never act externally without the approval queue.
    """
    if _learning is None or not _learning.self_learning_enabled(CONFIG):
        return ""
    try:
        hint = _learning.classify_feedback(message)
        if not hint:
            return ""
        rec = _learning.make_correction(message, hint=hint, source="chat")
        _learning.enqueue(COS_DIR, rec)
        try:
            spawn_background(
                [
                    CLAUDE_BIN, "-p", "/global:cos-learn --next", *model_args("learn"),
                    "--permission-mode", "dontAsk",
                    "--allowedTools", LEARN_TOOLS,
                    "--output-format", "text",
                ], "learn.log", job="learn")
            return ("\n\n🧠 Noted as a correction (%s) — investigating in the "
                    "background why this was missed; the fix and reasoning will "
                    "land in lessons-learned." % rec["id"])
        except OSError:
            return ("\n\n🧠 Correction queued (%s); it will be processed on the "
                    "next poll cycle." % rec["id"])
    except Exception:  # pragma: no cover - defensive: chat must never break
        return ""


